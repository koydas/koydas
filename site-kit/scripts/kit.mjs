#!/usr/bin/env node
// site-kit tooling (ADR-0001). Node >= 20, no dependency.
//   node site-kit/scripts/kit.mjs build [--version X.Y.Z]            rewrite site-kit/KIT.json (hashes of every profile)
//   node site-kit/scripts/kit.mjs verify                              fail if KIT.json does not match the files
//   node site-kit/scripts/kit.mjs sync --target DIR --profile react|node     vendor the kit into DIR (writes DIR/KIT.json)
//   node site-kit/scripts/kit.mjs sync --python FILE                  rewrite the site-kit block of a Python module
//   node site-kit/scripts/kit.mjs print-python                        print the Python block (tests)
//   node site-kit/scripts/kit.mjs check --target DIR | --python FILE  fail if the vendored copy differs from this kit
// Hash: sha256 over `<path> <sha256(bytes)>\n` of the profile's files, sorted by path.
import { createHash } from 'node:crypto';
import { cpSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseArgs } from 'node:util';

export const KIT_DIR = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const COMMON = ['tokens.css', 'shell.css', 'nav.json', 'header.html', 'footer.html', 'pagehead.html'];
export const PROFILES = {
  react: [...COMMON, 'render.mjs', 'react/SiteShell.tsx'],
  node: [...COMMON, 'render.mjs'],
  python: [...COMMON, 'render.py'],
};
export const BEGIN = '# BEGIN site-kit';
export const END = '# END site-kit';

const sha = (buf) => createHash('sha256').update(buf).digest('hex');
export const profileHash = (files) => sha(Object.keys(files).sort().map((p) => `${p} ${files[p]}\n`).join(''));

function hashFiles(dir, list) {
  return Object.fromEntries([...list].sort().map((p) => [p, sha(readFileSync(join(dir, p)))]));
}

const readKit = () => JSON.parse(readFileSync(join(KIT_DIR, 'KIT.json'), 'utf8'));

export function buildManifest(version) {
  const profiles = {};
  for (const [name, list] of Object.entries(PROFILES)) {
    const files = hashFiles(KIT_DIR, list);
    profiles[name] = { hash: profileHash(files), files };
  }
  return { name: 'site-kit', version, profiles };
}

/** The KIT.json a repo carries next to its vendored copy. */
export function vendoredManifest(profile) {
  const kit = readKit();
  const p = kit.profiles[profile];
  return { name: 'site-kit', version: kit.version, profile, hash: p.hash, files: p.files };
}

export function pythonBlock() {
  const m = vendoredManifest('python');
  const lit = (s) => JSON.stringify(s);
  const files = Object.keys(m.files).filter((f) => f !== 'render.py');
  const lines = [
    `${BEGIN} (generated by koydas/koydas site-kit/scripts/kit.mjs sync --python: edit the kit, not this block)`,
    '# fmt: off',
    `SK_VERSION = ${lit(m.version)}`,
    `SK_PROFILE = "python"`,
    `SK_HASH = ${lit(m.hash)}`,
    'SK_FILE_HASHES = {',
    ...Object.entries(m.files).map(([f, h]) => `    ${lit(f)}: ${lit(h)},`),
    '}',
    'SK_FILES = {',
    ...files.map((f) => `    ${lit(f)}: ${lit(readFileSync(join(KIT_DIR, f), 'utf8'))},  # noqa: E501`),
    '}',
    readFileSync(join(KIT_DIR, 'render.py'), 'utf8').trimEnd(),
    '# fmt: on',
    END,
  ];
  return lines.join('\n');
}

function replaceBlock(source, block) {
  const start = source.indexOf(BEGIN);
  const end = source.indexOf(END);
  if (start < 0 || end < start) throw new Error(`no "${BEGIN}" … "${END}" block found`);
  const endLine = source.indexOf('\n', end);
  return source.slice(0, start) + block + (endLine < 0 ? '' : source.slice(endLine));
}

function sync({ target, profile, python }) {
  if (python) {
    const file = resolve(python);
    writeFileSync(file, replaceBlock(readFileSync(file, 'utf8'), pythonBlock()));
    return `site-kit ${readKit().version} → ${file} (python block)`;
  }
  const list = PROFILES[profile];
  if (!list) throw new Error('--profile must be one of: ' + Object.keys(PROFILES).join(', '));
  const dir = resolve(target);
  for (const f of list) {
    mkdirSync(dirname(join(dir, f)), { recursive: true });
    cpSync(join(KIT_DIR, f), join(dir, f));
  }
  writeFileSync(join(dir, 'KIT.json'), JSON.stringify(vendoredManifest(profile), null, 2) + '\n');
  return `site-kit ${readKit().version} (${profile}) → ${dir}`;
}

export function check({ target, python }) {
  const problems = [];
  if (python) {
    const src = readFileSync(resolve(python), 'utf8');
    const start = src.indexOf(BEGIN);
    const end = src.indexOf(END);
    if (start < 0 || end < start) return ['no site-kit block'];
    const block = src.slice(start, src.indexOf('\n', end) < 0 ? src.length : src.indexOf('\n', end));
    if (block !== pythonBlock()) problems.push('python block differs from this kit');
    return problems;
  }
  const dir = resolve(target);
  const declared = JSON.parse(readFileSync(join(dir, 'KIT.json'), 'utf8'));
  const expected = vendoredManifest(declared.profile);
  for (const f of Object.keys(expected.files)) {
    if (!existsSync(join(dir, f))) problems.push(`missing ${f}`);
    else if (sha(readFileSync(join(dir, f))) !== expected.files[f]) problems.push(`${f} differs`);
  }
  if (declared.version !== expected.version) problems.push(`version ${declared.version} ≠ ${expected.version}`);
  if (declared.hash !== expected.hash) problems.push(`hash ${declared.hash} ≠ ${expected.hash}`);
  return problems;
}

export function verify() {
  const kit = readKit();
  const fresh = buildManifest(kit.version);
  return JSON.stringify(fresh) === JSON.stringify(kit) ? [] : ['KIT.json is stale: run `node site-kit/scripts/kit.mjs build`'];
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const [cmd, ...rest] = process.argv.slice(2);
  const { values } = parseArgs({ args: rest, options: { target: { type: 'string' }, profile: { type: 'string' }, python: { type: 'string' }, version: { type: 'string' } } });
  try {
    if (cmd === 'build') {
      const version = values.version ?? (existsSync(join(KIT_DIR, 'KIT.json')) ? readKit().version : '1.0.0');
      writeFileSync(join(KIT_DIR, 'KIT.json'), JSON.stringify(buildManifest(version), null, 2) + '\n');
      console.log(`KIT.json written (${version})`);
    } else if (cmd === 'verify' || cmd === 'check') {
      const problems = cmd === 'verify' ? verify() : check(values);
      if (problems.length) { console.error(problems.join('\n')); process.exit(1); }
      console.log('ok');
    } else if (cmd === 'print-python') {
      process.stdout.write(pythonBlock() + '\n');
    } else if (cmd === 'sync') {
      const problems = verify();
      if (problems.length) throw new Error(problems.join('\n'));
      console.log(sync(values));
    } else {
      console.error('usage: kit.mjs build|verify|sync|check (see header)'); process.exit(2);
    }
  } catch (e) { console.error(e.message); process.exit(1); }
}
